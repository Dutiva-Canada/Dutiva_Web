/*
 * Generate shared Supabase Database types for the Vite client and Deno edge
 * functions from the linked project (requires SUPABASE_ACCESS_TOKEN) or from
 * --project-id.
 *
 * Outputs:
 *   src/lib/supabase/database.types.ts
 *   supabase/functions/_shared/database.types.ts
 */

import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { cleanSecret } from './lib/secrets.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const header = '/* Generated by npm run db:types — do not edit by hand. */\n\n'
const clientPath = path.join(root, 'src', 'lib', 'supabase', 'database.types.ts')
const edgePath = path.join(root, 'supabase', 'functions', '_shared', 'database.types.ts')

const projectRef = cleanSecret(process.env.SUPABASE_PROJECT_REF) ?? 'khtwpxnvziiyplaflwru'

mkdirSync(path.dirname(clientPath), { recursive: true })

let types
try {
  types = execFileSync(
    'npx',
    ['supabase', 'gen', 'types', 'typescript', '--project-id', projectRef],
    { cwd: root, encoding: 'utf8', env: process.env },
  )
} catch (error) {
  console.error(
    'generate-db-types: failed — set SUPABASE_ACCESS_TOKEN and SUPABASE_PROJECT_REF, ' +
      'or run: npx supabase gen types typescript --project-id <ref> > src/lib/supabase/database.types.ts',
  )
  throw error
}

const body = `${header}${types}`
writeFileSync(clientPath, body)
copyFileSync(clientPath, edgePath)
console.log(`generate-db-types: wrote ${clientPath} and ${edgePath}`)
